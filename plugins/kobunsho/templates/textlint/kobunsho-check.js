// kobunsho: 文脈によって正誤が変わる語の辞書（@textlint-ja/textlint-rule-morpheme-match 用）
//
// 根拠は「公用文作成の考え方」（令和4年1月7日 文化審議会建議）。
// ここに載せる語は、仮名で書くべき場合と漢字で書くべき場合が品詞だけでは区別できない。
// そのため .textlintrc.json では警告（warning）として読み込み、書き手が文脈で判断する。

"use strict";

const PREFIX = "【kobunsho:要確認】";

// 形式名詞。具体的な対象を指す場合は漢字のまま（建議 解説 Ⅰ-1(3)ア）
const keishikimeishi = [
  ["事", "こと", "「事は重大である」のように具体的な事柄を指す場合"],
  ["時", "とき", "「法律の定める年齢に達した時」のように特定の時点を指す場合"],
  ["所", "ところ", "「家を建てる所」のように場所を指す場合"],
  ["物", "もの", "「所持する物」のように具体的な物体を指す場合"],
  ["者", "もの", "「裁判所の指名した者」のように特定の人を指す場合"]
].map(([kanji, kana, exception]) => ({
  message: `${PREFIX}形式名詞なら「${kana}」と仮名で書く。${exception}は漢字のままでよい。`,
  tokens: [{ surface_form: kanji, pos: "名詞", pos_detail_1: "非自立" }]
}));

// ある・ない。有無の対照、所在・存在の強調は漢字（建議 解説 Ⅰ-1(3)ウ）
const aruNai = [
  {
    message: `${PREFIX}「問題がある」のように仮名で書く。「財産が有る」「有り・無し」のように有無を対照させる場合は漢字のままでよい。`,
    tokens: [{ pos: "動詞", basic_form: "有る" }]
  },
  {
    message: `${PREFIX}「日本はアジアの東にある」のように仮名で書く。所在・存在を強調する場合は漢字のままでよい。`,
    tokens: [{ pos: "動詞", basic_form: "在る" }]
  },
  {
    message: `${PREFIX}「欠点がない」のように仮名で書く。「有り・無し」のように有無を対照させる場合は漢字のままでよい。`,
    tokens: [{ pos: "形容詞", basic_form: "無い" }]
  }
];

// 補助動詞の「見る」「頂く」。補助動詞でも形態素解析で「自立」と判定されるため、
// 実際に見る・もらう意味（地図を広げて見る）と区別できない（建議 解説 Ⅰ-1(3)ア）
const hojodoushi = ["て", "で"].flatMap((particle) => [
  {
    message: `${PREFIX}補助動詞なら「〜てみる」と仮名で書く。実際に目で見る意味なら漢字のままでよい。`,
    tokens: [{ surface_form: particle, pos: "助詞", pos_detail_1: "接続助詞" }, { pos: "動詞", basic_form: "見る" }]
  },
  {
    message: `${PREFIX}補助動詞なら「〜ていただく」と仮名で書く。実際に物をもらう意味なら漢字のままでよい。`,
    tokens: [{ surface_form: particle, pos: "助詞", pos_detail_1: "接続助詞" }, { pos: "動詞", basic_form: "頂く" }]
  }
]);

// 「等」「など」は慎重に使う（建議 Ⅱ-5イ(ウ)）
const nado = [
  {
    message: `${PREFIX}「等」「など」は、示すべきものを全て挙げられるなら使わない。使う場合は、前に代表的なものを置く。`,
    tokens: [{ surface_form: "等", pos: "名詞", pos_detail_1: "接尾" }]
  }
];

// 回りくどい言い方（建議 Ⅱ-5ウ(イ)）。「計画を実施する」のように意味が変わる場合は残す
const jisshi = [
  {
    message: `${PREFIX}「調査を実施した→調査した」のように短くできないか。言い換えると意味が変わる場合はそのままでよい。`,
    tokens: [
      { pos: "名詞", pos_detail_1: "サ変接続" },
      { surface_form: "を", pos: "助詞" },
      { surface_form: "実施", pos: "名詞" },
      { pos: "動詞", basic_form: "する" }
    ]
  }
];

// 「べく」は使わない（建議 Ⅲ-1オ）
const beku = [
  {
    message: `${PREFIX}「べく」は使わない。「〜するよう」「〜するために」などに言い換える。`,
    tokens: [{ surface_form: "べく", pos: "助動詞" }]
  }
];

// 外来語の長音。英語の -ry、-ty で終わる語は長音符号を付けるのが原則（建議 解説 Ⅰ-3エ）。
// 開発分野では慣用が割れているため警告にとどめる。プロジェクトで表記が決まっていればそれに従う。
const choon = [
  "メモリ", "ディレクトリ", "リポジトリ", "ライブラリ", "カテゴリ", "セキュリティ",
  "プロパティ", "ユーティリティ", "エンティティ", "クエリ", "エントリ", "レジストリ",
  "ファクトリ", "ヒストリ", "バイナリ", "サマリ", "クオリティ", "コミュニティ",
  "アクセシビリティ", "スケーラビリティ", "テレメトリ"
].map((word) => ({
  message: `${PREFIX}原則は長音符号を付けて「${word}ー」と書く。プロジェクトで表記が決まっていればそれに従い、文書内で統一する。`,
  tokens: [{ surface_form: word }]
}));

module.exports = [...keishikimeishi, ...aruNai, ...hojodoushi, ...nado, ...jisshi, ...beku, ...choon];
